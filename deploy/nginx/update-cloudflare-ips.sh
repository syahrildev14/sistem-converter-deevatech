#!/bin/sh
# Membuat /etc/nginx/conf.d/cloudflare-realip.conf dari daftar IP resmi Cloudflare,
# agar Nginx (dan rate-limit login aplikasi) melihat IP asli pengunjung, bukan IP Cloudflare.
#
# Jalankan: sudo sh deploy/nginx/update-cloudflare-ips.sh
# Opsional cron bulanan: 0 4 1 * * /bin/sh /opt/office-media-converter/deploy/nginx/update-cloudflare-ips.sh
set -eu

OUT=/etc/nginx/conf.d/cloudflare-realip.conf
TMP=$(mktemp)

{
  echo "# Generated by update-cloudflare-ips.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  for ip in $(curl -fsS https://www.cloudflare.com/ips-v4) $(curl -fsS https://www.cloudflare.com/ips-v6); do
    echo "set_real_ip_from $ip;"
  done
  echo "real_ip_header CF-Connecting-IP;"
} > "$TMP"

# Sanity check: harus berisi minimal beberapa rentang IP.
if [ "$(grep -c set_real_ip_from "$TMP")" -lt 5 ]; then
  echo "Gagal mengambil daftar IP Cloudflare" >&2
  rm -f "$TMP"
  exit 1
fi

mv "$TMP" "$OUT"
chmod 644 "$OUT"
nginx -t && systemctl reload nginx
echo "OK: $OUT diperbarui"
